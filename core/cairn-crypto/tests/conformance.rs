use cairn_crypto::CryptoBackend;

fn sha384_abc_matches_fips_180_example<B: CryptoBackend>() {
    assert_eq!(
        B::sha384(b"abc"),
        [
            0xcb, 0x00, 0x75, 0x3f, 0x45, 0xa3, 0x5e, 0x8b, 0xb5, 0xa0, 0x3d, 0x69, 0x9a, 0xc6,
            0x50, 0x07, 0x27, 0x2c, 0x32, 0xab, 0x0e, 0xde, 0xd1, 0x63, 0x1a, 0x8b, 0x60, 0x5a,
            0x43, 0xff, 0x5b, 0xed, 0x80, 0x86, 0x07, 0x2b, 0xa1, 0xe7, 0xcc, 0x23, 0x58, 0xba,
            0xec, 0xa1, 0x34, 0xc8, 0x25, 0xa7,
        ]
    );
}

fn hmac_sha384_matches_rfc4231_case_one<B: CryptoBackend>() {
    let expected = [
        0xaf, 0xd0, 0x39, 0x44, 0xd8, 0x48, 0x95, 0x62, 0x6b, 0x08, 0x25, 0xf4, 0xab, 0x46, 0x90,
        0x7f, 0x15, 0xf9, 0xda, 0xdb, 0xe4, 0x10, 0x1e, 0xc6, 0x82, 0xaa, 0x03, 0x4c, 0x7c, 0xeb,
        0xc5, 0x9c, 0xfa, 0xea, 0x9e, 0xa9, 0x07, 0x6e, 0xde, 0x7f, 0x4a, 0xf1, 0x52, 0xe8, 0xb2,
        0xfa, 0x9c, 0xb6,
    ];
    let tag = B::hmac_sha384(&[0x0b; 20], b"Hi There").unwrap();
    assert_eq!(&*tag, &expected);
}

fn hkdf_sha384_matches_wycheproof_case_one<B: CryptoBackend>() {
    let input = [
        0x24, 0xae, 0xff, 0x26, 0x45, 0xe3, 0xe0, 0xf5, 0x49, 0x4a, 0x9a, 0x10, 0x27, 0x78, 0xc4,
        0x3a,
    ];
    let expected = [
        0x4b, 0x70, 0x45, 0x42, 0x3d, 0x91, 0x56, 0x42, 0x4b, 0x0b, 0x85, 0xd9, 0x5a, 0x7d, 0x60,
        0x2f, 0xba, 0x39, 0x24, 0xb1,
    ];
    let output = B::hkdf_sha384(&input, &[], &[], 20).unwrap();
    assert_eq!(&output[..], &expected);
}

