use std::collections::BTreeMap;

use crate::{
    error::{Error::Rejected, Result},
    query::{Kind, Query},
    syntax::{tokens, trim},
};

const MALFORMED: &str = "native certificate: malformed term";

// Natural sums are flattened and their summands sorted, so equal renderings
// decide equality modulo associativity and commutativity of `tamtplus`.
#[derive(Clone)]
enum Canonical {
    Sum(Vec<String>),
    Other(String),
}

impl Canonical {
    fn render(self) -> String {
        match self {
            Self::Sum(summands) => format!("tamtplus({})", summands.join(",")),
            Self::Other(text) => text,
        }
    }
}

fn apply(name: &str, arguments: Vec<Canonical>) -> Canonical {
    if name == "tamtplus" {
        let mut summands = Vec::new();
        for argument in arguments {
            match argument {
                Canonical::Sum(inner) => summands.extend(inner),
                Canonical::Other(text) => summands.push(text),
            }
        }
        summands.sort_unstable();
        Canonical::Sum(summands)
    } else {
        let arguments: Vec<_> = arguments.into_iter().map(Canonical::render).collect();
        Canonical::Other(format!("{name}({})", arguments.join(",")))
    }
}

fn canonical(text: &str, substitution: &BTreeMap<&str, Canonical>) -> Result<Canonical> {
    let tokens = tokens(trim(text))?;
    let mut frames: Vec<(&str, Vec<Canonical>)> = Vec::new();
    let mut position = 0;
    loop {
        let token = *tokens.get(position).ok_or(Rejected(MALFORMED))?;
        position += 1;
        if matches!(token, "(" | ")" | ",") {
            return Err(Rejected(MALFORMED));
        }
        if tokens.get(position) == Some(&"(") {
            position += 1;
            frames.push((token, Vec::new()));
            continue;
        }
        let mut value = substitution
            .get(token)
            .cloned()
            .unwrap_or_else(|| Canonical::Other(token.to_owned()));
        loop {
            let Some(frame) = frames.last_mut() else {
                return if position == tokens.len() {
                    Ok(value)
                } else {
                    Err(Rejected(MALFORMED))
                };
            };
            frame.1.push(value);
            match tokens.get(position) {
                Some(&",") => {
                    position += 1;
                    break;
                }
                Some(&")") => {
                    position += 1;
                    let (name, arguments) = frames.pop().ok_or(Rejected(MALFORMED))?;
                    value = apply(name, arguments);
                }
                _ => return Err(Rejected(MALFORMED)),
            }
        }
    }
}

// A unifier must make both sides of every equation AC-equal; a matcher must
// instantiate the pattern to an AC-equal copy of the unchanged subject.
pub fn check(query: &Query, bindings: &BTreeMap<&str, &str>) -> Result<()> {
    let identity = BTreeMap::new();
    let mut substitution = BTreeMap::new();
    for (variable, text) in bindings {
        substitution.insert(*variable, canonical(text, &identity)?);
    }
    let subject = if query.kind == Kind::Match {
        &identity
    } else {
        &substitution
    };
    for [left, right] in query.sides.as_chunks::<2>().0 {
        if canonical(left, &substitution)?.render() != canonical(right, subject)?.render() {
            return Err(Rejected("native reply: solution does not solve the query"));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use super::canonical;

    // Generated by QueryModuleExport.lean; each pair's verdict is `nativeACEqual`.
    const CORPUS: &str = include_str!("../tests/syntax_corpus.txt");

    fn render(text: &str) -> String {
        let Ok(value) = canonical(text, &BTreeMap::new()) else {
            panic!("certificate rejected Lean rendering {text}");
        };
        value.render()
    }

    #[test]
    fn certificate_agrees_with_the_lean_ac_corpus() {
        let (mut equal, mut distinct) = (0, 0);
        for line in CORPUS.lines() {
            match line.split('\t').collect::<Vec<_>>().as_slice() {
                ["EQUAL", left, right] => {
                    assert_eq!(render(left), render(right), "{left} vs {right}");
                    equal += 1;
                }
                ["DISTINCT", left, right] => {
                    assert_ne!(render(left), render(right), "{left} vs {right}");
                    distinct += 1;
                }
                _ => {}
            }
        }
        assert!(equal > 0 && distinct > 0);
    }
}
