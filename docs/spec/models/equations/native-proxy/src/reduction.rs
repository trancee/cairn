use crate::{
    certificate,
    error::Result,
    unifier::{Tree, message, render},
};

// Mirrors `nativeSortedNormalize` (QueryNormalization.lean): children first, then one root step.
// `native_sorted_reduce_certificate`: for a message query, a reply is a correct reduction iff it
// is AC-equal to this normal form.
pub fn normalize(tree: &Tree) -> Result<Tree> {
    let Tree::Apply(name, children) = tree else {
        return Ok(tree.clone());
    };
    let children = children.iter().map(normalize).collect::<Result<Vec<_>>>()?;
    root(Tree::Apply(name.clone(), children))
}

fn constant(name: &str) -> Tree {
    Tree::Apply(name.to_owned(), Vec::new())
}

fn is<'a>(tree: &'a Tree, symbol: &str) -> Option<&'a [Tree]> {
    match tree {
        Tree::Apply(name, children) if name == symbol => Some(children),
        _ => None,
    }
}

fn opens(payload: &Tree, first: &Tree, second: &Tree) -> Result<bool> {
    Ok(message(payload)
        && message(first)
        && certificate::equivalent(&render(first), &render(second))?)
}

// `nativeRootRewrite`, defaulting to the unchanged term as in `nativeRootStep`.
fn root(tree: Tree) -> Result<Tree> {
    let rewritten = match &tree {
        Tree::Apply(name, children) => match (name.as_str(), children.as_slice()) {
            ("tamXCflip", [role]) if is(role, "tamXCroleA") == Some(&[]) => {
                Some(constant("tamXCroleB"))
            }
            ("tamXCflip", [role]) if is(role, "tamXCroleB") == Some(&[]) => {
                Some(constant("tamXCroleA"))
            }
            ("tamXCfst" | "tamXCsnd", [pair]) => match is(pair, "tamXCpair") {
                Some([left, right]) if message(left) && message(right) => {
                    Some(if name == "tamXCfst" {
                        left.clone()
                    } else {
                        right.clone()
                    })
                }
                _ => None,
            },
            ("tamXCsdec", [cipher, second]) => match is(cipher, "tamXCsenc") {
                Some([payload, first]) if opens(payload, first, second)? => Some(payload.clone()),
                _ => None,
            },
            ("tamXCkdec", [cipher, second]) => match is(cipher, "tamXCkem") {
                Some([payload, key]) => match is(key, "tamXCpk") {
                    Some([first]) if opens(payload, first, second)? => Some(payload.clone()),
                    _ => None,
                },
                _ => None,
            },
            _ => None,
        },
        Tree::Variable(_) => None,
    };
    Ok(rewritten.unwrap_or(tree))
}

#[cfg(test)]
mod tests {
    use super::normalize;
    use crate::unifier::{parse, render};

    // Generated by QueryModuleExport.lean from `nativeSortedNormalize`.
    const CORPUS: &str = include_str!("../tests/syntax_corpus.txt");

    #[test]
    fn normalizer_agrees_with_the_lean_reduce_corpus() {
        let (mut changed, mut stuck) = (0, 0);
        for line in CORPUS.lines() {
            let ["REDUCE", term, normal] = line.split('\t').collect::<Vec<_>>().as_slice()[..]
            else {
                continue;
            };
            let Some(tree) = parse(term) else {
                panic!("parser rejected Lean rendering {term}");
            };
            let Ok(result) = normalize(&tree) else {
                panic!("normalizer failed on {term}");
            };
            assert_eq!(render(&result), normal, "{term}");
            if term == normal {
                stuck += 1;
            } else {
                changed += 1;
            }
        }
        assert!(changed > 0 && stuck > 0);
    }
}
